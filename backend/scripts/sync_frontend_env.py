"""
Generate frontend/.env from backend/.env.

Only the two values the browser is allowed to have: the project URL and the
anon key. Both are public by design — RLS is what protects the data, not key
secrecy. The service key and DATABASE_URL must never reach the frontend, so
this script copies a fixed allowlist rather than everything.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[2]
BACKEND_ENV = ROOT / "backend" / ".env"
FRONTEND_ENV = ROOT / "frontend" / ".env"

load_dotenv(BACKEND_ENV)

url = os.environ.get("SUPABASE_URL", "")
anon = os.environ.get("SUPABASE_ANON_KEY", "")

if not url or not anon or "PASTE" in url or "PASTE" in anon:
    sys.exit("SUPABASE_URL / SUPABASE_ANON_KEY are not set in backend/.env")

use_mocks = "--mocks" in sys.argv

FRONTEND_ENV.write_text(
    "\n".join(
        [
            "# Generated by backend/scripts/sync_frontend_env.py — do not edit by hand.",
            "# Anything here is shipped to the browser. Never add the service key.",
            "",
            f"VITE_SUPABASE_URL={url}",
            f"VITE_SUPABASE_ANON_KEY={anon}",
            "",
            "# false = talk to the real backend and database.",
            f"VITE_USE_MOCKS={'true' if use_mocks else 'false'}",
            "VITE_API_BASE=/api",
            "",
        ]
    ),
    encoding="utf-8",
)

print(f"Wrote {FRONTEND_ENV.relative_to(ROOT)}")
print(f"  VITE_SUPABASE_URL      {url}")
print(f"  VITE_SUPABASE_ANON_KEY set ({len(anon)} chars)")
print(f"  VITE_USE_MOCKS         {'true' if use_mocks else 'false'}")
